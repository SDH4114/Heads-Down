// Builds the Chrome / Edge package (Manifest V3) from the same sources as the Firefox add-on.
// manifest.json stays the source of truth for name, version, scripts and pages.
// Usage: node scripts/build-chromium.mjs [--zip]   ->  dist/chromium/ (+ dist/heads-down-chromium-<version>.zip)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.join(ROOT, "dist");
const OUT = path.join(DIST, "chromium");
const base = JSON.parse(fs.readFileSync(path.join(ROOT, "manifest.json"), "utf8"));

// Chromium does not accept SVG extension icons.
const ICONS = Object.fromEntries([16, 32, 48, 128].map((size) => [size, `icons/icon-${size}.png`]));

const manifest = {
  manifest_version: 3,
  name: base.name,
  version: base.version,
  description: base.description,
  default_locale: base.default_locale,
  // 116: notifications.create returns a promise. The `browser` alias covers versions before 148.
  minimum_chrome_version: "116",
  icons: ICONS,
  // WithHostAccess: redirect rules need host access anyway, and this variant adds no extra warning.
  permissions: ["storage", "tabs", "notifications", "alarms", "declarativeNetRequestWithHostAccess"],
  host_permissions: ["<all_urls>"],
  background: { service_worker: "sw.js" },
  action: {
    default_title: base.browser_action.default_title,
    default_popup: base.browser_action.default_popup,
    default_icon: ICONS,
  },
  options_ui: base.options_ui,
  // Redirect rules may only send requests to web-accessible pages.
  web_accessible_resources: [{ resources: base.web_accessible_resources, matches: ["<all_urls>"] }],
};

for (const file of Object.values(ICONS)) {
  if (!fs.existsSync(path.join(ROOT, file))) throw new Error(`Missing ${file}`);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const filter = (src) => path.basename(src) !== ".DS_Store";
for (const dir of ["_locales", "icons", "src", "ui"]) fs.cpSync(path.join(ROOT, dir), path.join(OUT, dir), { recursive: true, filter });
fs.copyFileSync(path.join(ROOT, "LICENSE"), path.join(OUT, "LICENSE"));
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
// A service worker is one file: it loads the background scripts in the manifest's order.
const scripts = base.background.scripts.map((file) => JSON.stringify(file)).join(",\n  ");
fs.writeFileSync(path.join(OUT, "sw.js"), `// Generated by scripts/build-chromium.mjs from manifest.json.\nimportScripts(\n  ${scripts}\n);\n`);
console.log(`Built ${path.relative(ROOT, OUT)} (version ${base.version})`);

if (process.argv.includes("--zip")) {
  const zip = path.join(DIST, `heads-down-chromium-${base.version}.zip`);
  fs.rmSync(zip, { force: true });
  execFileSync("zip", ["-qr", zip, "."], { cwd: OUT });
  console.log(`Packed ${path.relative(ROOT, zip)}`);
}
